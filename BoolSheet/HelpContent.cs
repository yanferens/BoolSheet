    public const string UsageTitle = "Як користуватися BoolSheet";

    public const string Usage =
        """
        Робота з клітинками
        • Клацніть клітинку, щоб вибрати її; подвійне клацання — одразу до редагування.
        • Введіть вираз у рядку формули вгорі й натисніть Enter або «Застосувати».
          Якщо просто клацнути іншу клітинку, вираз теж буде застосовано.
        • Кнопка «Режим» (Ctrl+E) перемикає показ виразів або їхніх значень.
        • Наведіть мишу на клітинку, щоб побачити вираз, значення або опис помилки.

        Що можна писати у виразах
        • цілі числа довільної довжини: 123456789012345678901234567890
        • від'ємні числа та унарний мінус: -5, -A1, -(2 + 3), 2 - -3
        • посилання на клітинки: A1, B12 (регістр не важливий)
        • арифметика: +  -  *  /  mod  div
        • порівняння: =  <>  <  >  <=  >=
        • заперечення: not
        • круглі дужки
        • адреса клітинки — одна літера A–Z і номер рядка; до 1000 символів у виразі

        Значення
        • 0 — хибність, будь-яке інше число (зокрема від'ємне) — істина.
        • Порівняння та not дають ІСТИНА або ХИБНІСТЬ.
        • Порожня клітинка дорівнює 0.
        • /  — ділення з відкиданням дробової частини, div — з округленням вниз, mod — остача.
        • not на початку стосується всього виразу: not A1 > 2 = not (A1 > 2);
          усередині виразу — лише одного операнда: A1 = not B1, 1 + not 0.
        • = порівнює числа: (2 > 1) = 5 — ХИБНІСТЬ, бо ІСТИНА — це 1, а не 5.
        • Числа до ~30 000 цифр; довгі показуються у вигляді 1.2345E+99.

        Приклади
        A1 + 5 > B2
        not (A1 mod 2 = 0)
        (A1 <= 10) = (B1 >= 3)

        Значення в клітинках
        • числа вирівняно праворуч, ІСТИНА — зеленим, ХИБНІСТЬ — помаранчевим,
          клітинки з помилкою підсвічено червоним.

        Рядки та стовпчики додаються й видаляються кнопками на панелі або в меню «Таблиця».
        Світла чи темна тема вмикається разом з темою Windows.
        Рядок чи стовпчик, на який посилаються інші клітинки, видалити не можна.
        """;

